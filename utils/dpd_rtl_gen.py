# DPD RTL vector/ROM generator (Step 4D.1/4D.5, 2026-08-22).
# Single source of truth for:
#   1. Xilinx/dpd_lag_rom.svh  — the 39-term lag-tuple ROM include
#   2. Xilinx/Testbench/dpd_cal_img.mem — cal_coef_store image (both channels)
#   3. Xilinx/Testbench/dpd_golden.mem  — input vectors + expected NS codes
# Arithmetic here is the EXACT RTL fixed point (dpd_fx_golden.py semantics,
# W=18 / F=24, 56-bit accumulator): every loop operation mirrors dpd_engine.sv
# + noise_shaper_ef3.sv Stage E bit-for-bit.
#
# NOTE on the lag tuples: the frozen cosim80c3j kernel npy files live outside
# the repo (LTspice work area). Until Step 6.4 cal tooling exports the real
# tuple list, this file DEFINES the ROM as the canonical 39-term basis:
# all 21 order-2 pairs (i<=j<=5) + the first 18 order-3 triples (i<=j<=k<=5,
# lexicographic). Coefficient VALUES always come from the ARM at runtime, so
# a tuple-basis swap is a one-file regen + resynth with no interface change.
import numpy as np
import os

HERE = os.path.dirname(os.path.abspath(__file__))
XIL = os.path.join(HERE, "..", "Xilinx")
TBD = os.path.join(XIL, "Testbench")

FRAC = 42
LSB = 1 << FRAC
CLAMP = 63 * LSB
F = 24                      # action grid 2^-24 code-LSB (W18/F24 ratified)
ACCW = 56                   # accumulator width (wraps like the RTL)
NTERMS = 39
NFIR = 16
HL = 17                     # history depth: max(lag 5, FIR j+1 = 16) + 1

# --- 1. Lag tuple basis ------------------------------------------------------
pairs2 = [(i, j) for i in range(6) for j in range(i, 6)]              # 21
triples = [(i, j, k) for i in range(6) for j in range(i, 6)
           for k in range(j, 6)][:18]                                  # 18
tuples = [t + (7,) * (3 - len(t)) for t in pairs2 + triples]           # 7=unused
assert len(tuples) == NTERMS

# --- Cal store word layout (per channel, addr[8]=channel) --------------------
#    0- 63 : lut24[code]  24-bit signed, 2^-24 code-LSB grid
#   64-102 : Qm[39]       18-bit signed mantissa (word[17:0])
#  103-118 : Fm[16]       18-bit signed mantissa
#  119     : shQ[5:0]   120: shS[5:0]   121: shF[5:0]   122: GF[5:0] (= G-24)
#  128-191 : Sm[64]       18-bit signed mantissa
A_LUT, A_Q, A_F, A_SHQ, A_SHS, A_SHF, A_GF, A_S = 0, 64, 103, 119, 120, 121, 122, 128

rng = np.random.default_rng(2026)

def make_coefs(seed):
    r = np.random.default_rng(seed)
    return {
        # full W18 range is legal; scaled here so corrections land ~±1 code LSB
        # (realistic loop dynamics, no permanent clamping in the vectors)
        "Qm":  r.integers(-4096, 4096, NTERMS),
        "Sm":  r.integers(-131072, 131072, 64),
        "Fm":  r.integers(-16384, 16384, NFIR),
        "lut": r.integers(-(1 << 20), 1 << 20, 64),
        # realistic shared-exponent shifts (G=35: exQ=-34, exS=-18, exF=-25)
        "shQ": 1, "shS": 17, "shF": 10, "GF": 11,
    }

def sx(v, w):
    """wrap to w-bit signed"""
    m = (1 << w) - 1
    v &= m
    return v - (1 << w) if v >= (1 << (w - 1)) else v

def dpd_corr(c, hist, code):
    """EXACT dpd_engine arithmetic: 56-bit acc, returns corr at FRAC scale."""
    acc = -(int(c["Sm"][code]) << c["shS"])
    for (l0, l1, l2), qm in zip(tuples, c["Qm"]):
        prod = hist[l0] * hist[l1] * (1 if l2 == 7 else hist[l2])
        acc += (int(qm) * prod) << c["shQ"]
    for j in range(NFIR):
        acc -= (int(c["Fm"][j]) * hist[j + 1]) << c["shF"]
    acc = sx(acc, ACCW)
    half = 1 << (c["GF"] - 1)
    act = sx(acc + half, ACCW) >> c["GF"]              # 2^-24 grid
    return (int(c["lut"][code]) + act) << (FRAC - F)   # FRAC scale

def run(u, dith, c, dpd_on):
    """noise_shaper_ef3 + Stage-E patch, integer exact."""
    e1 = e2 = e3 = f1 = f2 = f3 = 0
    hist = [0] * HL
    out = np.empty(len(u), dtype=np.int64)
    for k in range(len(u)):
        f = ((e1 + (e1 >> 1)) - ((e2 << 1) + (e2 >> 2)) + (e3 - (e3 >> 3))
             + (f1 + (f1 >> 1)) - ((f2 >> 1) + (f2 >> 2)) + (f3 >> 3))
        w = int(u[k]) + (32 << FRAC) + f
        code = (w + int(dith[k])) >> FRAC
        code = 0 if code < 0 else (63 if code > 63 else code)
        e_raw = w - (code << FRAC)
        if dpd_on:
            hist = [code - 32] + hist[:HL - 1]
            e = e_raw - dpd_corr(c, hist, code)
        else:
            e = e_raw
        e = CLAMP if e > CLAMP else (-CLAMP if e < -CLAMP else e)
        e1, e2, e3, f1, f2, f3 = e, e1, e2, f, f1, f2
        out[k] = code
    return out

# --- 2. Emit the lag ROM include ---------------------------------------------
with open(os.path.join(XIL, "dpd_lag_rom.svh"), "w") as fh:
    fh.write("// GENERATED by utils/dpd_rtl_gen.py — DO NOT EDIT.\n")
    fh.write("// 39-term Volterra lag-tuple ROM ({lag2,lag1,lag0}, 3'd7 = unused).\n")
    fh.write("// Basis: 21 order-2 pairs + 18 order-3 triples, max lag 5.\n")
    fh.write("localparam int unsigned DPD_NTERMS = 39;\n")
    fh.write("localparam logic [8:0] DPD_LAGS [0:38] = '{\n")
    rows = [f"    9'b{t[2]:03b}_{t[1]:03b}_{t[0]:03b}" for t in tuples]
    fh.write(",\n".join(rows) + "\n};\n")

# --- 3. Cal image + vectors ---------------------------------------------------
cal = [make_coefs(101), make_coefs(202)]          # ch 0 (L), ch 1 (R)
img = [0] * 512
for ch, c in enumerate(cal):
    base = ch << 8
    for i in range(64):
        img[base + A_LUT + i] = int(c["lut"][i]) & 0xFFFFFF
    for i in range(NTERMS):
        img[base + A_Q + i] = int(c["Qm"][i]) & 0x3FFFF
    for i in range(NFIR):
        img[base + A_F + i] = int(c["Fm"][i]) & 0x3FFFF
    img[base + A_SHQ] = c["shQ"]
    img[base + A_SHS] = c["shS"]
    img[base + A_SHF] = c["shF"]
    img[base + A_GF]  = c["GF"]
    for i in range(64):
        img[base + A_S + i] = int(c["Sm"][i]) & 0x3FFFF

with open(os.path.join(TBD, "dpd_cal_img.mem"), "w") as fh:
    for wv in img:
        fh.write(f"{wv:06x}\n")

M = 2000
n = np.arange(M)
HD = LSB
amp = 28.0 * 10 ** (-1 / 20)
vec = {}
for ch in range(2):
    u = np.concatenate([
        (amp * np.sin(2 * np.pi * (17 + 6 * ch) * n[:1000] / 2048) * LSB).astype(np.int64),
        rng.integers(-20 * LSB, 20 * LSB, 1000),
    ])
    dith = (rng.integers(0, HD, M) + rng.integers(0, HD, M) - HD).astype(np.int64)
    y_on = run(u, dith, cal[ch], True)
    y_off = run(u, dith, cal[ch], False)
    vec[ch] = (u, dith, y_on, y_off)

# format per line: u[48] d[43->44 hex pad] y_on[8] y_off[8], L then R interleaved
with open(os.path.join(TBD, "dpd_golden.mem"), "w") as fh:
    for k in range(M):
        for ch in range(2):
            u, d, yon, yoff = vec[ch]
            fh.write(f"{int(u[k]) & ((1<<48)-1):012x}"
                     f"{int(d[k]) & ((1<<43)-1):011x}"
                     f"{int(yon[k]):02x}{int(yoff[k]):02x}\n")

print(f"wrote dpd_lag_rom.svh (39 tuples), dpd_cal_img.mem (512 words), "
      f"dpd_golden.mem ({M} vectors x 2ch); "
      f"code ranges L {vec[0][2].min()}..{vec[0][2].max()} "
      f"R {vec[1][2].min()}..{vec[1][2].max()}")
